def count_residues(pdb_string: str) -> int:
    """Count residues with N, CA and C atoms present (those ProteinMPNN can use)."""
    atoms: dict[tuple[str, str, str], set[str]] = {}
    for line in pdb_string.splitlines():
        if line.startswith("ATOM"):
            key = (line[21], line[22:26].strip(), line[26].strip())
            atoms.setdefault(key, set()).add(line[12:16].strip())
    return sum(1 for names in atoms.values() if {"N", "CA", "C"} <= names)
